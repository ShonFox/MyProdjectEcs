// Interfaces/IAbility.cs
using UnityEngine;

/// <summary>
/// Общий контракт любой способности (стрельба, рывок, лечение и т.д.).
/// Логика способности живёт в обычном MonoBehaviour — так её удобно
/// настраивать в инспекторе и перетаскивать между объектами.
///
/// Почему метод принимает isPressed:
/// система способностей вызывает Execute каждый кадр.
/// Флаг isPressed говорит: кнопка прямо сейчас зажата или нет.
/// Благодаря этому способность сама понимает разницу:
///   - игрок ТОЛЬКО ЧТО нажал кнопку  -> мгновенный выстрел;
///   - игрок ДЕРЖИТ кнопку            -> выстрел раз в ShootDelay секунд;
///   - игрок ОТПУСТИЛ кнопку          -> сброс состояния.
/// </summary>
public interface IAbility
{
    /// <summary>isPressed = true, пока кнопка действия зажата, false — когда отпущена.</summary>
    void Execute(bool isPressed);
}
