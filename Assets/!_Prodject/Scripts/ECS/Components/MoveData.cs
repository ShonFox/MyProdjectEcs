// Components/MoveData.cs
using Unity.Entities;

/// <summary>
/// Параметры движения сущности.
/// Важно: здесь НЕТ ничего про спринт. Спринт — отдельный компонент SprintData
/// и отдельная система. Если завтра спринт перестанет быть нужен,
/// мы просто удалим его файлы и движение продолжит работать.
/// Так системы не «прилипают» друг к другу и легко переносятся между проектами.
/// </summary>
public struct MoveData : IComponentData
{
    /// <summary>Базовая скорость. Задаётся один раз в инспекторе, юнитов в секунду.</summary>
    public float BaseSpeed;

    /// <summary>
    /// Актуальная скорость: то, что реально использует CharacterMoveSystem.
    /// Базовая после старта, но системы-модификаторы (спринт, замедление...)
    /// могут её перезаписать. Само движение про спринт не знает.
    /// </summary>
    public float Speed;
}
