// Components/LookData.cs — полная замена
using Unity.Entities;

/// <summary>
/// Настройки follow-камеры. Углы тут больше не хранятся:
/// камера берёт направление спины у самой модели персонажа.
/// </summary>
public struct LookData : IComponentData
{
    /// <summary>Расстояние камеры от персонажа, юниты.</summary>
    public float Distance;

    /// <summary>На какой высоте над персонажем смотреть, юниты. ~1.5 — уровень груди.</summary>
    public float Height;

    /// <summary>
    /// Скорость, с которой камера «догоняет» поворот персонажа.
    /// 1 — мгновенно (камера приклеена к спине), 0.1 — еле поспевает.
    /// Значения около 5 дают приятную плавность без сильного отставания.
    /// </summary>
    public float FollowSpeed;

    /// <summary>
    /// Насколько камера поднята НАД точкой обзора, юниты.
    /// 0 — камера на уровне точки (смотрит горизонтально),
    /// 1–2 — камера выше головы, смотрит слегка сверху.
    /// </summary>
    public float Elevation;
}
